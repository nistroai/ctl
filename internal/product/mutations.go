type inputField struct{ key, kind, help string }

func mutationFields(product, tier, action string) ([]inputField, []string) {
	if action == "update" {
		if product == "inference" {
			return []inputField{{"replicas", "int", "Fixed replica count from 1 to 8"}}, []string{"replicas"}
		}
		fields := []inputField{{"storage_gib", "number", "New storage size in GiB; expansion only"}}
		if tier == "base" {
			return append(fields, inputField{"vcpu", "number", "New vCPUs; memory is calculated at 4 GiB per vCPU"}), nil
		}
		return append(fields, inputField{"postgres_version", "string", "New PostgreSQL major version; upgrade only"}, inputField{"replicas", "int", "Standby replicas from 0 to 8"}, inputField{"enable_superuser", "bool", "Enable superuser access"}, inputField{"parameters", "map", "PostgreSQL parameter name=value (repeatable; replaces the parameter set)"}), nil
	}
	fields := []inputField{{"location", "string", "Required location: US, EU, or ASIA"}}
	required := []string{"location"}
	if product == "postgres" {
		fields = append(fields, inputField{"storage_gib", "number", "Required storage size in GiB"}, inputField{"database_name", "string", "Database name (default app)"}, inputField{"database_username", "string", "Database username (default app)"}, inputField{"database_password", "string", "Database password (generated by server when omitted)"})
		required = append(required, "storage_gib")
		if tier == "base" {
			fields = append(fields, inputField{"vcpu", "number", "Required vCPUs from 1 to 8; memory is 4 GiB per vCPU"})
			required = append(required, "vcpu")
		} else {
			fields = append(fields, inputField{"replicas", "int", "Standby replicas from 0 to 8 (default 1)"}, inputField{"enable_superuser", "bool", "Enable superuser access (default false)"}, inputField{"parameters", "map", "PostgreSQL parameter name=value (repeatable)"}, inputField{"extensions", "array", "Extensions (comma-separated)"})
		}
	} else {
		fields = append(fields, inputField{"model_url", "string", "Required Hugging Face model URL or ID"}, inputField{"max_model_len", "int", "Required context length in tokens"}, inputField{"quantization", "string", "Quantization (default Auto)"}, inputField{"gpu_type", "string", "GPU type (default Any)"})
		required = append(required, "model_url", "max_model_len")
		if tier == "scale" {
			fields = append(fields, inputField{"replicas", "int", "Required fixed replica count from 1 to 8"})
			required = append(required, "replicas")
		}
	}
	if tier == "scale" {
		fields = append(fields, inputField{"cloud", "string", "Required cloud provider"}, inputField{"region", "string", "Required cloud region"}, inputField{"instance_type", "string", "Required instance type"})
		required = append(required, "cloud", "region", "instance_type")
	}
	return fields, required
}

func AddMutations(parent *cobra.Command, deps Deps, path string) {
	for _, action := range []string{"create", "update"} {
		group := &cobra.Command{Use: action, Short: action + " a deployment by tier", Args: cobra.NoArgs}
		for _, tier := range []string{"base", "scale"} {
			if parent.Name() == "inference" && action == "update" && tier == "base" {
				continue
			}
			fields, required := mutationFields(parent.Name(), tier, action)
			use, count := tier, 0
			if action == "update" {
				use, count = tier+" ID", 1
			}
			cmd := &cobra.Command{Use: use, Short: action + " a " + tier + " " + parent.Name() + " deployment", Args: cobra.ExactArgs(count), Long: "Provide all required settings with flags or --config-file. JSON keys use underscores; flags use hyphens. Flags override JSON values. No interactive prompts or event watcher are started."}
			cmd.Flags().String("config-file", "", "JSON configuration file; use - to read from stdin")
			for _, field := range fields {
				name := strings.ReplaceAll(field.key, "_", "-")
				switch field.kind {
				case "int":
					cmd.Flags().Int(name, 0, field.help)
				case "number":
					cmd.Flags().Float64(name, 0, field.help)
				case "bool":
					cmd.Flags().Bool(name, false, field.help)
				case "array":
					cmd.Flags().StringSlice(name, nil, field.help)
				case "map":
					cmd.Flags().StringArray(name, nil, field.help)
				default:
					cmd.Flags().String(name, "", field.help)
				}
			}
			cmd.RunE = func(cmd *cobra.Command, args []string) error {
				format, _ := cmd.Flags().GetString("output")
				if format != "table" && format != "json" {
					return fmt.Errorf("output must be table or json")
				}
				body, err := mutationInput(cmd, fields)
				if err != nil {
					return err
				}
				if parent.Name() == "postgres" && tier == "scale" && action == "create" {
					if _, supplied := body["replicas"]; !supplied {
						body["replicas"] = 1
					}
				}
				if err := requireFields(body, required); err != nil {
					return err
				}
				if len(body) == 0 {
					return fmt.Errorf("provide at least one update field or --config-file")
				}
				if err := validateMutation(body, parent.Name(), tier, action); err != nil {
					return err
				}
				ctx, cancel := context.WithTimeout(cmd.Context(), 2*time.Minute)
				defer cancel()
				client := deps.Client()
				resourcePath, method := path, "POST"
				if action == "update" {
					id := args[0]
					if strings.TrimSpace(id) == "" || strings.ContainsAny(id, "/\\?#") || id == "." || id == ".." {
						return fmt.Errorf("invalid resource ID %q", id)
					}
					resourcePath, method = path+"/"+url.PathEscape(id), "PATCH"
					raw, err := client.Resource(ctx, "GET", resourcePath, nil)
					if err != nil {
						return err
					}
					var current map[string]any
					if err := json.Unmarshal(raw, &current); err != nil {
						return err
					}
					if dep, ok := current["deployment"].(map[string]any); ok {
						current = dep
					}
					if output.DeploymentTier(current) != tier {
						return fmt.Errorf("deployment does not belong to the %s tier", tier)
					}
				} else {
					body["pricing_mode"] = "basic"
					if tier == "scale" {
						body["pricing_mode"] = "dedicated"
					}
					if parent.Name() == "postgres" {
						body["postgres_version"] = "ghcr.io/cloudnative-pg/postgresql:18"
						if tier == "scale" {
							// The pinned catalog offer provides the CPU and memory for Scale.
							request := map[string]any{}
							for k, v := range body {
								request[k] = v
							}
							request["vcpu"], request["memory_gib"] = 0.5, 2
							raw, err := client.Resource(ctx, "POST", "/v1/postgres/offers", request)
							if err != nil {
								return err
							}
							var offers struct {
								Options []map[string]any `json:"deployment_options"`
							}
							if err := json.Unmarshal(raw, &offers); err != nil {
								return err
							}
							found := false
							for _, offer := range offers.Options {
								if offer["cloud"] == body["cloud"] && offer["region"] == body["region"] && offer["instance_type"] == body["instance_type"] && number(offer["vcpu"]) > 0 && number(offer["ram_gib"]) > 0 {
									body["vcpu"], body["memory_gib"] = offer["vcpu"], offer["ram_gib"]
									found = true
									break
								}
							}
							if !found {
								return fmt.Errorf("no Postgres offer matches the requested cloud, region, and instance type")
							}
						}
					} else {
						body["enable_prefix_caching"], body["enable_chunked_prefill"] = true, true
						if tier == "base" {
							body["min_replicas"], body["max_replicas"] = 0, 1
						}
					}
				}
				var progress *progressLine
				if format != "json" {
					progress = startProgress(cmd.ErrOrStderr(), map[string]string{"create": "Creating deployment", "update": "Updating deployment"}[action])
				}
				raw, err := client.Resource(ctx, method, resourcePath, body)
				if progress != nil {
					progress.finish("Deployment "+action+" request accepted", err == nil)
				}
				if err != nil {
					return err
				}
				if parent.Name() == "postgres" {
					raw, err = withoutMonthlyOfferPrice(raw)
					if err != nil {
						return err
					}
				}
				return output.Print(cmd.OutOrStdout(), raw, format)
			}
			group.AddCommand(cmd)
		}
		parent.AddCommand(group)
	}
}

func mutationInput(cmd *cobra.Command, fields []inputField) (map[string]any, error) {
	body := map[string]any{}
	file, _ := cmd.Flags().GetString("config-file")
	if file != "" {
		reader := cmd.InOrStdin()
		if file != "-" {
			f, err := os.Open(file)
			if err != nil {
				return nil, err
			}
			defer f.Close()
			reader = f
		}
		data, err := io.ReadAll(io.LimitReader(reader, (1<<20)+1))
		if err != nil {
			return nil, err
		}
		if len(data) > 1<<20 {
			return nil, fmt.Errorf("configuration exceeds 1 MiB")
		}
		decoder := json.NewDecoder(strings.NewReader(string(data)))
		decoder.UseNumber()
		if err := decoder.Decode(&body); err != nil || body == nil {
			return nil, fmt.Errorf("config-file must contain a JSON object")
		}
		if decoder.Decode(new(any)) != io.EOF {
			return nil, fmt.Errorf("config-file must contain exactly one JSON object")
		}
	}
	allowed := map[string]bool{}
	for _, field := range fields {
		allowed[field.key] = true
		name := strings.ReplaceAll(field.key, "_", "-")
		if cmd.Flags().Changed(name) {
			switch field.kind {
			case "int":
				body[field.key], _ = cmd.Flags().GetInt(name)
			case "number":
				body[field.key], _ = cmd.Flags().GetFloat64(name)
			case "bool":
				body[field.key], _ = cmd.Flags().GetBool(name)
			case "array":
				body[field.key], _ = cmd.Flags().GetStringSlice(name)
			case "map":
				values, _ := cmd.Flags().GetStringArray(name)
				params := map[string]string{}
				for _, value := range values {
					key, setting, ok := strings.Cut(value, "=")
					if !ok || strings.TrimSpace(key) == "" {
						return nil, fmt.Errorf("--%s requires name=value", name)
					}
					params[strings.TrimSpace(key)] = setting
				}
				body[field.key] = params
			default:
				body[field.key], _ = cmd.Flags().GetString(name)
			}
		}
		if value, ok := body[field.key]; ok {
			valid := false
			switch field.kind {
			case "number", "int":
				n := number(value)
				valid = !math.IsNaN(n) && !math.IsInf(n, 0)
				if field.kind == "int" {
					valid = valid && math.Trunc(n) == n
				}
			case "bool":
				_, valid = value.(bool)
			case "string":
				_, valid = value.(string)
			case "array":
				switch v := value.(type) {
				case []string:
					valid = true
				case []any:
					valid = true
					for _, item := range v {
						if _, ok := item.(string); !ok {
							valid = false
						}
					}
				}
			case "map":
				switch v := value.(type) {
				case map[string]string:
					valid = true
				case map[string]any:
					valid = true
					for _, item := range v {
						if _, ok := item.(string); !ok {
							valid = false
						}
					}
				}
			}
			if !valid {
				return nil, fmt.Errorf("%s must have type %s", field.key, field.kind)
			}
		}
	}
	for key := range body {
		if !allowed[key] {
			return nil, fmt.Errorf("field %s is not supported by this command", key)
		}
	}
	return body, nil
}

func number(value any) float64 {
	switch v := value.(type) {
	case int:
		return float64(v)
	case float64:
		return v
	case json.Number:
		n, err := v.Float64()
		if err == nil {
			return n
		}
	}
	return math.NaN()
}

func requireFields(body map[string]any, required []string) error {
	for _, key := range required {
		value, ok := body[key]
		if !ok || value == nil {
			return fmt.Errorf("%s is required (use --%s or --config-file)", key, strings.ReplaceAll(key, "_", "-"))
		}
		if s, ok := value.(string); ok && strings.TrimSpace(s) == "" {
			return fmt.Errorf("%s is required (use --%s or --config-file)", key, strings.ReplaceAll(key, "_", "-"))
		}
	}
	return nil
}

func validateMutation(body map[string]any, product, tier, action string) error {
	for key, limits := range map[string][2]float64{"vcpu": {1, 8}, "storage_gib": {10, 4096}, "max_model_len": {1, 2000000}, "replicas": {0, 8}} {
		if value, ok := body[key]; ok {
			if key == "vcpu" && (tier == "scale" || action == "update") {
				limits[0] = 0.000001
				if tier == "scale" {
					limits[1] = math.Inf(1)
				}
			}
			if key == "storage_gib" && tier == "base" {
				limits[1] = 1024
			}
			if key == "replicas" && product == "inference" {
				limits[0] = 1
			}
			n := number(value)
			fractionAllowed := key == "vcpu" && (tier == "scale" || action == "update")
			if n < limits[0] || n > limits[1] || math.IsNaN(n) || (!fractionAllowed && math.Trunc(n) != n) {
				return fmt.Errorf("%s must be an integer from %g to %g", key, limits[0], limits[1])
			}
		}
	}
	if value, ok := body["location"]; ok {
		location := strings.ToUpper(strings.TrimSpace(value.(string)))
		if location != "US" && location != "EU" && location != "ASIA" {
			return fmt.Errorf("location must be US, EU, or ASIA")
		}
		body["location"] = location
	}
	for key, value := range body {
		if s, ok := value.(string); ok && key != "database_password" && strings.TrimSpace(s) == "" {
			return fmt.Errorf("%s must not be empty", key)
		}
	}
	if product == "postgres" {
		if value, ok := body["vcpu"]; ok && (tier == "base" || body["memory_gib"] == nil) {
			body["memory_gib"] = number(value) * 4
		}
	}
	if product == "inference" {
		if value, ok := body["replicas"]; ok {
			body["min_replicas"], body["max_replicas"] = value, value
			delete(body, "replicas")
		}
		for _, key := range []string{"quantization", "gpu_type"} {
			if value, ok := body[key].(string); ok && (strings.EqualFold(value, "Auto") || strings.EqualFold(value, "Any")) {
				delete(body, key)
			}
		}
	}
	return nil
}
